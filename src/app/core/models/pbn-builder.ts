import { GeneratedHandPair, Vulnerability } from '../../hand-generation/models/hand-generation-api.models';
import { CardCode, DECK, ranksForSuit, SUIT_CHARS } from './cards';
import { Player, PLAYER_PBN_CHAR} from './players';

const vulnerabilityMap: Record<Vulnerability, string> = {
  NONE: 'None',
  NS: 'NS',
  EW: 'EW',
  BOTH: 'Both',
};

const pbnDealOrder: Player[] = ['NORTH', 'EAST', 'SOUTH', 'WEST'];


export interface PbnDeal {
  board: number;
  dealer: Player;
  vulnerability: Vulnerability;
  hands: Partial<Record<Player, CardCode[]>>;
}

export function handPairToPbn(handPair: GeneratedHandPair): string {
  return pbnDealToPbn({
    board: handPair.board,
    dealer: handPair.dealer,
    vulnerability: handPair.vulnerability,
    hands: handPair.hands,
  });
}

export function pbnDealToPbn(pbnDeal: PbnDeal): string {
  const completedHands = completeHands(pbnDeal.hands);

  return [
    `% Generated by Bridge Angular`,
    `[Board "${pbnDeal.board}"]`,
    `[Dealer "${PLAYER_PBN_CHAR[pbnDeal.dealer]}"]`,
    `[Vulnerable "${vulnerabilityMap[pbnDeal.vulnerability]}"]`,
    `[Deal "N:${pbnDealOrder.map((player) => handToPbn(completedHands[player])).join(' ')}"]`,
    '',
  ].join('\n');
}

function completeHands(hands: Partial<Record<Player, CardCode[]>>): Record<Player, CardCode[]> {
  const completedHands: Record<Player, CardCode[]> = {
    NORTH: [...(hands.NORTH ?? [])],
    EAST: [...(hands.EAST ?? [])],
    SOUTH: [...(hands.SOUTH ?? [])],
    WEST: [...(hands.WEST ?? [])],
  };

  const knownCards = Object.values(completedHands).flat();
  const uniqueKnownCards = new Set(knownCards);

  if (uniqueKnownCards.size !== knownCards.length) {
    throw new Error('Cannot export PBN because the generated hand contains duplicate cards.');
  }

  const remainingCards = shuffleDeck(DECK.filter((card) => !uniqueKnownCards.has(card)));

  let remainingCardIndex = 0;

  for (const player of pbnDealOrder) {
    const playerCards = completedHands[player];

    if (playerCards.length > 13) {
      throw new Error(`Cannot export PBN because ${player} has more than 13 cards.`);
    }

    while (playerCards.length < 13) {
      const nextCard = remainingCards[remainingCardIndex];

      if (!nextCard) {
        throw new Error('Cannot export PBN because there are not enough remaining cards to complete the deal.');
      }

      playerCards.push(nextCard);
      remainingCardIndex++;
    }
  }

  const totalCards = Object.values(completedHands).flat();
  const totalUniqueCards = new Set(totalCards);

  if (totalCards.length !== 52 || totalUniqueCards.size !== 52) {
    throw new Error('Cannot export PBN because the completed deal does not contain 52 unique cards.');
  }

  return completedHands;
}

function shuffleDeck  (array: CardCode[]) {
  for (let i = array.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [array[i], array[j]] = [array[j], array[i]];
  }
  return array;
}

function handToPbn(cards: CardCode[]): string {
  return SUIT_CHARS
    .map((suit) => ranksForSuit(cards, suit))
    .join('.');
}
